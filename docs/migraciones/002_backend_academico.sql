-- Migración académica independiente del login. Ejecutar una sola pieza en Neon.
-- Conserva filas, claves existentes y la columna histórica notafinal.
BEGIN;
SET LOCAL lock_timeout = '5s';
LOCK TABLE universidaduees.matricula, universidaduees.estudiantes,
           universidaduees.calificaciones IN SHARE ROW EXCLUSIVE MODE;
ALTER TABLE universidaduees.asignaturas ADD COLUMN IF NOT EXISTS codigo varchar(30);
ALTER TABLE universidaduees.matricula
    ADD COLUMN IF NOT EXISTS matricula_id integer GENERATED BY DEFAULT AS IDENTITY;
CREATE UNIQUE INDEX IF NOT EXISTS matricula_id_unico ON universidaduees.matricula(matricula_id);

-- Las PK existentes permanecen intactas. Los nuevos IDs empiezan tras el máximo actual.
DO $$
DECLARE item record; siguiente bigint;
BEGIN
    FOR item IN SELECT * FROM (VALUES
        ('estudiantes','estudianteid'), ('calificaciones','calificacionid')
    ) AS columnas(tabla,columna) LOOP
        IF EXISTS (SELECT 1 FROM information_schema.columns
            WHERE table_schema='universidaduees' AND table_name=item.tabla
              AND column_name=item.columna AND is_identity='NO' AND column_default IS NULL) THEN
            EXECUTE format('SELECT coalesce(max(%I),0)+1 FROM universidaduees.%I',item.columna,item.tabla) INTO siguiente;
            EXECUTE format('ALTER TABLE universidaduees.%I ALTER COLUMN %I ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)',item.tabla,item.columna,siguiente);
        END IF;
    END LOOP;
END $$;

-- Permite guardar registros incompletos. Los CHECK 0..10 y las FK permanecen.
ALTER TABLE universidaduees.calificaciones
    ALTER COLUMN nota1 DROP NOT NULL,
    ALTER COLUMN nota2 DROP NOT NULL,
    ALTER COLUMN nota3 DROP NOT NULL,
    ALTER COLUMN notafinal DROP NOT NULL;
ALTER TABLE universidaduees.calificaciones
    ADD COLUMN IF NOT EXISTS nota_final_calculada numeric(5,2)
    GENERATED ALWAYS AS (
        CASE WHEN nota1 IS NULL OR nota2 IS NULL OR nota3 IS NULL THEN NULL
        ELSE round(nota1*0.30 + nota2*0.30 + nota3*0.40,2) END
    ) STORED;

CREATE TABLE IF NOT EXISTS universidaduees.publicaciones_registros (
    asignaturaid integer NOT NULL REFERENCES universidaduees.asignaturas(asignaturaid),
    registro smallint NOT NULL CHECK (registro IN (1,2,3)),
    publicado boolean NOT NULL DEFAULT false,
    actualizado_en timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (asignaturaid,registro)
);
CREATE INDEX IF NOT EXISTS matricula_estudiante_idx ON universidaduees.matricula(estudianteid);
COMMIT;

SELECT (SELECT count(*) FROM universidaduees.estudiantes) AS estudiantes,
       (SELECT count(*) FROM universidaduees.matricula) AS matriculas,
       (SELECT count(*) FROM universidaduees.calificaciones) AS calificaciones;
